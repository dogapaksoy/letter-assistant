// Bundles src/server/extract-letter.ts for the Supabase Edge Function (Deno) and writes
// a deno.json that maps every external npm package to the exact version installed here,
// so the function runs the same library versions as the tests.
// Usage: npm run functions:build

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { build } from 'esbuild';

const root = join(import.meta.dirname, '..');
const outDir = join(root, 'supabase', 'functions', 'extract-letter');

// Packages loaded by Deno from npm instead of being bundled.
const EXTERNAL = ['zod', 'unpdf', '@anthropic-ai/sdk', '@google/genai', '@mistralai/mistralai'];

function installedVersion(name) {
  const pkgPath = join(root, 'node_modules', ...name.split('/'), 'package.json');
  return JSON.parse(readFileSync(pkgPath, 'utf8')).version;
}

await build({
  entryPoints: [join(root, 'src', 'server', 'extract-letter.ts')],
  outfile: join(outDir, 'handler.js'),
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  external: EXTERNAL.flatMap((name) => [name, `${name}/*`]),
  banner: { js: '// GENERATED by scripts/build-function.mjs - do not edit.' },
  logLevel: 'warning',
});

const imports = Object.fromEntries(
  EXTERNAL.flatMap((name) => {
    const version = installedVersion(name);
    return [
      [name, `npm:${name}@${version}`],
      [`${name}/`, `npm:/${name}@${version}/`],
    ];
  }),
);
writeFileSync(join(outDir, 'deno.json'), JSON.stringify({ imports }, null, 2) + '\n');

console.log(`Built ${join('supabase', 'functions', 'extract-letter')} (handler.js, deno.json)`);
